#!/usr/bin/env python3
"""
Borguerie Center static site generator.

Renders the pages that used to be generated by the PHP scripts in legacy/src
(index.php, rss.php, api.php) into _site/, ready to be served by GitHub Pages.
"""

import json
import re
import shutil
import subprocess
from datetime import datetime, timezone
from email.utils import format_datetime
from html import escape as html_escape
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

SITE_URL = "https://borguerie.outadoc.fr"

ROOT = Path(__file__).resolve().parent
PUBLIC_DIR = ROOT / "public"
TEMPLATES_DIR = ROOT / "templates"
MP3_DIR = PUBLIC_DIR / "mp3"
PUBDATES_FILE = ROOT / "pubdates.json"
OUT_DIR = ROOT / "_site"

MP3_PATTERN = re.compile(r"^borg_(\d+)\.mp3$")


def render(template, **values):
    return re.sub(r"\{\{(\w+)\}\}", lambda m: values[m.group(1)], template)


def git_commit_date(path):
    """Date of the commit that added the file, for mp3s missing from pubdates.json."""
    try:
        out = subprocess.run(
            ["git", "log", "--diff-filter=A", "--format=%aI", "-1", "--", path.name],
            cwd=path.parent, capture_output=True, text=True, check=True,
        ).stdout.strip()
        if out:
            return datetime.fromisoformat(out)
    except (OSError, subprocess.CalledProcessError):
        pass
    return datetime.now(timezone.utc)


def list_episodes():
    pubdates = json.loads(PUBDATES_FILE.read_text(encoding="utf-8"))
    episodes = []
    for path in MP3_DIR.iterdir():
        match = MP3_PATTERN.match(path.name)
        if not match:
            continue
        ep_id = match.group(1)
        if ep_id in pubdates:
            pubdate = datetime.fromisoformat(pubdates[ep_id])
        else:
            pubdate = git_commit_date(path)
        episodes.append({
            "id": ep_id,
            "path": f"mp3/{path.name}",
            "url": f"{SITE_URL}/mp3/{path.name}",
            "pubdate": pubdate,
        })
    episodes.sort(key=lambda ep: int(ep["id"]), reverse=True)
    return episodes


def build_index(episodes):
    page = (TEMPLATES_DIR / "index.html").read_text(encoding="utf-8")
    row = (TEMPLATES_DIR / "episode-row.html").read_text(encoding="utf-8")
    rows = "".join(render(row, id=html_escape(ep["id"])) for ep in episodes)
    (OUT_DIR / "index.html").write_text(render(page, episodes=rows), encoding="utf-8")


def build_feed(episodes):
    last_build = max(ep["pubdate"] for ep in episodes)
    items = "".join(
        "<item>"
        f"<title>Appload #{xml_escape(ep['id'])}</title>"
        f"<description>La borguerie de l'épisode #{xml_escape(ep['id'])} d'Appload !</description>"
        f"<link>{xml_escape(ep['url'])}</link>"
        f"<guid>{xml_escape(ep['url'])}</guid>"
        f"<pubDate>{format_datetime(ep['pubdate'])}</pubDate>"
        "</item>"
        for ep in episodes
    )
    feed = f"""<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0">
<channel>
	<title>Borguerie Center</title>
	<link>{SITE_URL}/</link>
	<description>Les borgueries de Jérôme Keinborg, juste au-dessus de votre clavier. Oui oui, là. Sur l'écran.</description>
	<language>fr-fr</language>
	<lastBuildDate>{format_datetime(last_build)}</lastBuildDate>
	<managingEditor>admin@outadoc.fr (Baptiste Candellier)</managingEditor>
	<webMaster>admin@outadoc.fr (Baptiste Candellier)</webMaster>
{items}
</channel>
</rss>
"""
    (OUT_DIR / "feed.rss").write_text(feed, encoding="utf-8")


def build_api(episodes):
    data = [
        {"id": ep["id"], "url": ep["url"], "pubdate": format_datetime(ep["pubdate"])}
        for ep in episodes
    ]
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    (OUT_DIR / "api.json").write_text(payload, encoding="utf-8")
    # Keep the legacy endpoint URL working
    (OUT_DIR / "api.php").write_text(payload, encoding="utf-8")


def main():
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    shutil.copytree(PUBLIC_DIR, OUT_DIR)

    episodes = list_episodes()
    build_index(episodes)
    build_feed(episodes)
    build_api(episodes)

    print(f"Built {len(episodes)} episodes into {OUT_DIR}")


if __name__ == "__main__":
    main()
